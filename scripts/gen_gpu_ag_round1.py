# Generate the v2 AG round-1 Metal kernel: direct-M encode as unrolled XOR
# chains (masks from evaluating the Paar SLP symbolically), products written
# per coordinate set, unrolled 32x32 transposes.
import re, sys
slp = open(sys.argv[1]).read()
body = slp[slp.index('unsafe {') + len('unsafe {'):]
body = body[:body.rindex('}')]
body = body[:body.rindex('}')]
masks = {}
def ev(expr):
    expr = expr.strip()
    m = re.fullmatch(r'veorq_u8\((.*)\)', expr)
    if m:
        inner = m.group(1)
        depth = 0
        for i, ch in enumerate(inner):
            if ch == '(': depth += 1
            elif ch == ')': depth -= 1
            elif ch == ',' and depth == 0:
                return ev(inner[:i]) ^ ev(inner[i + 1:])
        raise ValueError(expr)
    m = re.fullmatch(r'inp\[(\d+)\]', expr)
    if m: return 1 << int(m.group(1))
    if expr == 'vdupq_n_u8(0)': return 0
    return masks[expr]
M = [None] * 160
for line in body.strip().splitlines():
    line = line.strip().rstrip(';')
    if not line: continue
    m = re.fullmatch(r'let (s\d+) = (.*)', line)
    if m:
        masks[m.group(1)] = ev(m.group(2)); continue
    m = re.fullmatch(r'out\[(\d+)\] = (.*)', line)
    m and M.__setitem__(int(m.group(1)), ev(m.group(2)))
assert all(v is not None for v in M)
weights = [bin(v).count('1') for v in M]
print(f"// M: 160 rows, weights min {min(weights)} max {max(weights)} total {sum(weights)}", file=sys.stderr)

def chain(src, s):
    bits = [j for j in range(64) if (M[s] >> j) & 1]
    if not bits: return '0u'
    return ' ^ '.join(f'{src}[{j}]' for j in bits)

out = []
w = out.append
w("// AUTO-GENERATED by scratchpad gen_ag_v2.py from genus95_curve_code/slp_derived.rs:")
w("// the encode M (160x64) as direct XOR chains, evaluated symbolically from the SLP.")
w("")
w("// In-place 32x32 bit transpose, unrolled: afterwards a[p] bit i = old a[i] bit p.")
w("static inline void transpose32(thread uint* a) {")
w("    uint t;")
mask = 0x0000FFFF
j = 16
while j:
    k = 0
    while k < 32:
        w(f"    t = ((a[{k}] >> {j}u) ^ a[{k | j}]) & 0x{mask:08X}u; a[{k}] ^= t << {j}u; a[{k | j}] ^= t;")
        k = ((k | j) + 1) & ~j
    j >>= 1
    mask ^= (mask << j) & 0xFFFFFFFF if j else 0
w("}")
w("")
w("static inline void plane_words(device const uint2* rows, thread uint* planes) {")
w("    uint lo[32];")
w("    uint hi[32];")
for i in range(32):
    w(f"    {{ uint2 r = rows[{i}]; lo[{i}] = r.x; hi[{i}] = r.y; }}")
w("    transpose32(lo);")
w("    transpose32(hi);")
for p in range(32):
    w(f"    planes[{p}] = lo[{p}]; planes[{32 + p}] = hi[{p}];")
w("}")
w("")
# products for p in [lo, hi): slots base layout per set
def product_set(name, ps, with3):
    w(f"static inline void {name}(thread const uint* pa, thread const uint* pb, threadgroup uint* xch, uint lid) {{")
    n = len(ps)
    for i, p in enumerate(ps):
        w(f"    {{ // p = {p}")
        w(f"        uint a0 = {chain('pa', p)};")
        w(f"        uint b0 = {chain('pb', p)};")
        w(f"        uint a1 = {chain('pa', 64 + p)};")
        w(f"        uint b1 = {chain('pb', 64 + p)};")
        w(f"        xch[{i} * 32u + lid] = (a0 & pb[{p}]) ^ (pa[{p}] & b0);")
        w(f"        xch[{n + i} * 32u + lid] = (a1 & pb[{p}]) ^ (a0 & b0) ^ (pa[{p}] & b1);")
        if with3:
            w(f"        uint a2 = {chain('pa', 128 + p)};")
            w(f"        uint b2 = {chain('pb', 128 + p)};")
            w(f"        xch[{2 * n + i} * 32u + lid] = (a2 & pb[{p}]) ^ (a1 & b0) ^ (a0 & b1) ^ (pa[{p}] & b2);")
        w("    }")
    w("}")
    w("")
product_set("products_lo", list(range(32)), True)
product_set("products_hi", list(range(32, 64)), False)
print("\n".join(out))
